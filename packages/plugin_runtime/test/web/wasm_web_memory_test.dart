@TestOn('browser')
library;

import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:plugin_runtime/plugin_runtime.dart';

/// ブラウザで動かす確認 (D-452): `flutter test --platform chrome test/web`(packages/plugin_runtime で)。
///
/// Codex セキュリティ検査の指摘 `resource-exhaustion.web-wasm-memory-growth`: メモリの上限を実行の**後**にしか見ていなかったので、
/// 最大を宣言しないモジュールは `start` / `call` の中で上限を超えて `memory.grow` できた。起動前に最大を書き込む
/// ([capWasmMemory]) ので、ゲストの実行中に伸ばそうとしても -1 が返ることを、本物の Web Worker + ブラウザの WebAssembly で確かめる。

/// 最小の ABI を満たすモジュール(初期 1 ページ・**最大なし**)。`start` で `memory.grow(pages)` し、
/// snapshot は失敗(-1)なら "refused"、伸びたら "grown" を返す。
/// (wat: `(memory (export "memory") 1) (start $s) (func $s (global.set $g (memory.grow (i32.const pages))))` …)
Uint8List growModule(int pages) {
  assert(pages >= -8192 && pages < 8192);
  // i32.const の値は 2 バイトの符号付き LEB128 にしてある(長さを変えずに差し替えられるよう)。
  return Uint8List.fromList([
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x1c, 0x05, 0x60, 0x00, 0x00, 0x60, 0x01, 0x7f, 0x01, 0x7f, 0x60, 0x02, 0x7f, 0x7f, 0x00, 0x60, 0x00, 0x01, 0x7e, 0x60, 0x06, 0x7f, 0x7f, 0x7f, 0x7f, 0x7f, 0x7f, 0x01, 0x7e, 0x03, 0x07, 0x06, 0x00, 0x01, 0x02, 0x03, 0x03, 0x04, 0x05, 0x03, 0x01, 0x00, 0x01, 0x06, 0x06, 0x01, 0x7f, 0x01, 0x41, 0x00, 0x0b, 0x07, 0x36, 0x06, 0x06, 0x6d, 0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00, 0x05, 0x61, 0x6c, 0x6c, 0x6f, 0x63, 0x00, 0x01, 0x07, 0x64, 0x65, 0x61, 0x6c, 0x6c, 0x6f, 0x63, 0x00, 0x02, 0x08, 0x73, 0x6e, 0x61, 0x70, 0x73, 0x68, 0x6f, 0x74, 0x00, 0x03, 0x05, 0x70, 0x61, 0x74, 0x63, 0x68, 0x00, 0x04, 0x04, 0x63, 0x61, 0x6c, 0x6c, 0x00, 0x05, 0x08, 0x01, 0x00, 0x0a, 0x38, 0x06, 0x09, 0x00, 0x41,
    (pages & 0x7f) | 0x80, (pages >> 7) & 0x7f,
    0x40, 0x00, 0x24, 0x00, 0x0b, 0x05, 0x00, 0x41, 0x80, 0x08, 0x0b, 0x02, 0x00, 0x0b, 0x19, 0x00, 0x23, 0x00, 0x41, 0x7f, 0x46, 0x04, 0x7e, 0x42, 0x87, 0x80, 0x80, 0x80, 0x80, 0x02, 0x05, 0x42, 0x85, 0x80, 0x80, 0x80, 0x80, 0x04, 0x0b, 0x0b, 0x04, 0x00, 0x10, 0x03, 0x0b, 0x04, 0x00, 0x10, 0x03, 0x0b, 0x0b, 0x17, 0x02, 0x00, 0x41, 0x10, 0x0b, 0x07, 0x72, 0x65, 0x66, 0x75, 0x73, 0x65, 0x64, 0x00, 0x41, 0x20, 0x0b, 0x05, 0x67, 0x72, 0x6f, 0x77, 0x6e,
  ]);
}

void main() {
  test('最大を宣言しないモジュールが start の中で上限 (256 MiB) を超えて伸ばそうとしても、-1 が返る', () async {
    // 1 + 8191 ページ = 512 MiB。直す前は start の中で伸び、起動後の checkMemory まで止まらなかった。
    final w = await WasmPluginWorker.spawn(WasmWorkerConfig(wasmBytes: growModule(8191)));
    addTearDown(w.dispose);
    expect(await w.snapshot(), 'refused');
  });

  test('上限の内側なら伸ばせる(書き込んだ最大で、ふつうのプラグインは困らない)', () async {
    final w = await WasmPluginWorker.spawn(WasmWorkerConfig(wasmBytes: growModule(100)));
    addTearDown(w.dispose);
    expect(await w.snapshot(), 'grown');
  });
}
